const KOSMOS_DEEP = <<<'TXT'
РЕЖИМ: глубокая работа над задачей в фоне. Человек не ждёт у экрана: результат придёт ему отдельным сообщением.
- Работай основательно: план → выполнение → самопроверка.
- На ключевых шагах коротко сообщай ход работы через report_progress (одна строка).
- Итог — готовый результат в удобном виде: заголовки, списки, таблицы (markdown). В начале — короткий вывод.
TXT;

function sys_blocks(array $me, array $thread, string $mode): array {
  $blocks = [['type' => 'text', 'text' => KOSMOS_RULES . "\n\n" . ($mode === 'deep' ? KOSMOS_DEEP : KOSMOS_FAST),
              'cache_control' => ['type' => 'ephemeral']]];
  $ctx = 'Сейчас: ' . date('d.m.Y H:i') . ' (' . date_default_timezone_get() . ").\n"
       . 'Собеседник: ' . ($me['name'] !== '' ? $me['name'] : 'сотрудник') . ', роль ' . ($me['boss'] ? 'boss (руководитель)' : ($me['role'] ?: 'сотрудник')) . '.';
  $mem = mem_for($me);
  $comp = []; $user = [];
  foreach ($mem as $m) { $line = '- [№' . $m['id'] . '] ' . $m['text']; if ($m['scope'] === 'company') $comp[] = $line; else $user[] = $line; }
  $ctx .= "\n\nПАМЯТЬ О КОМПАНИИ:\n" . ($comp ? implode("\n", $comp) : '- пока пусто');
  $ctx .= "\n\nПАМЯТЬ О СОБЕСЕДНИКЕ:\n" . ($user ? implode("\n", $user) : '- пока пусто');
  if (($thread['summary'] ?? '') !== '') $ctx .= "\n\nСВОДКА НАЧАЛА ЭТОГО РАЗГОВОРА:\n" . $thread['summary'];
  $blocks[] = ['type' => 'text', 'text' => $ctx];
  return $blocks;
}

/* Последние сообщения разговора в пределах бюджета знаков; роли чередуются, первым идёт человек. */
function history(string $threadId, int $budget = 40000, int $afterId = 0): array {
  $q = db()->prepare('SELECT id, role, text, notes FROM messages WHERE thread_id=? AND id>? ORDER BY id DESC LIMIT 200');
  $q->execute([$threadId, $afterId]);
  $rows = []; $len = 0;
  foreach ($q->fetchAll() as $r) {
    $t = (string)$r['text'];
    $notes = json_decode((string)$r['notes'], true) ?: [];
    if ($notes) $t .= "\n[Сделано: " . implode('; ', array_map('strval', $notes)) . ']';
    $len += mb_strlen($t);
    if ($len > $budget && $rows) break;
    $rows[] = ['role' => $r['role'] === 'user' ? 'user' : 'assistant', 'text' => trim($t) !== '' ? $t : '…'];
  }
  $rows = array_reverse($rows);
  $out = [];
  foreach ($rows as $r) {
    if (!$out && $r['role'] !== 'user') continue;
    $n = count($out);
    if ($n && $out[$n - 1]['role'] === $r['role']) $out[$n - 1]['content'] .= "\n\n" . $r['text'];
    else $out[] = ['role' => $r['role'], 'content' => $r['text']];
  }
  return $out;
}
